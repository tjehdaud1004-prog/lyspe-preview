// 학습 질문에 흔한 말("맞았나요", "도와줘")은 일부러 넣지 않았다. 번호가 낱말 안에 들어 있으면("119쪽") 걸린다 — 애매하면 안내 쪽이다.
export const EMERGENCY_PATTERNS = Object.freeze([
  /죽고\s*싶|죽을래|죽어\s*버리|죽어버리|자살|자해|극단적\s*선택|목숨을?\s*끊|사라지고\s*싶|살기\s*싫|살고\s*싶지\s*않/,
  /살려\s*(줘|주세요|달라|주라)|살려요|구해\s*(줘|주세요)/,
  /(?<![\d])(?:119|112|109|1388)(?![\d])/,
  /신고\s*(해|할|하고|좀|부탁)|신고해\s*줘|경찰[^\s]{0,2}\s*(불러|부르|에)|구급차|응급실|응급\s*(상황|환자)/,
  /불이?\s*났|불났|화재|연기가\s*(나|차)|가스\s*(냄새|누출)/,
  /피가\s*(나|난|많|멈추|계속)|피를\s*(흘|토|많)|피\s*나|출혈|의식이?\s*(없|잃)|쓰러(졌|지)/,
  /숨(을|이)?\s*(못|안|막|쉬기\s*힘|쉴\s*수\s*없)|호흡\s*곤란|질식/,
  /(때려(?!\s*맞)|때렸|때리|폭행|구타|맞고\s*(있|왔|다녀))/,
  /(?:(?:아빠|엄마|형|오빠|언니|누나|선생님|친구|애들|누가)(?:한테|에게|가|이|께)|한테|에게)[^.?!]{0,8}맞았/,
  /납치|감금|유괴|성폭|성추행|성희롱|성적\s*(학대|접촉)|학대|스토킹|따라다니|몰래\s*촬영|불법\s*촬영/,
  /학교\s*폭력|학폭|왕따|집단\s*괴롭힘|괴롭힘을?\s*당/,
  /칼(로|을)?\s*(들|위협|찌)|흉기|총\s*(을|으로)|위협\s*(을|당)|협박/,
]);

export function looksLikeEmergency(text) {
  const s = String(text ?? '').normalize('NFC');
  if (s.trim() === '') return false;
  return EMERGENCY_PATTERNS.some((re) => re.test(s));
}
